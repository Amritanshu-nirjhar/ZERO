// The die-cut: every shape is drawn twice, first as a fat white rounded stroke (the sticker's
// backing, which follows the logo's outline), then as the logo itself on top.
function Mark({ s }: { s: (typeof STICKERS)[number] }) {
  const shapes = s.d ? [{ fill: s.color, d: s.d }] : MICROSOFT;
  return (
    <svg
      viewBox="-4.5 -4.5 33 33"
      className="h-full w-full overflow-visible [filter:drop-shadow(0.25cqw_0.4cqw_0.3cqw_rgba(40,25,5,0.45))]"
    >
      {shapes.map((sh) => (
        <path
          key={`b${sh.d}`}
          d={sh.d}
          fill="#fff"
          stroke="#fff"
          strokeWidth={6}
          strokeLinejoin="round"
        />
      ))}
      {shapes.map((sh) => (
        <path key={sh.d} d={sh.d} fill={sh.fill} />
      ))}
    </svg>
  );
}

function Sticker({
  p,
  i,
  s,
  still,
}: {
  p: MotionValue<number>;
  i: number;
  s: (typeof STICKERS)[number];
  still: boolean;
}) {
  // Slapped down one after another: comes in big and slightly turned, squashes flat, settles.
  const a = T.flick[1] + i * 0.012;
  const b = a + 0.03;
  const at = (f: number) => a + (b - a) * f;
  const scale = useTransform(p, [a, at(0.6), at(0.8), b], [1.5, 0.94, 1.03, 1]);
  const rotate = useTransform(p, [a, b], [s.rot - 18, s.rot]);
  const opacity = useTransform(p, [a, at(0.25)], [0, 1]);

  return (
    <motion.div
      style={{
        left: `${s.x}%`,
        top: `${s.y}%`,
        width: `${s.size}cqw`,
        height: `${s.size}cqw`,
        marginLeft: `${-s.size / 2}cqw`,
        marginTop: `${-s.size / 2}cqw`,
        ...(still ? { rotate: s.rot } : { scale, rotate, opacity }),
      }}
      className="absolute"
    >
      {/* Hover: the sticker lifts a little at the edge, like it's about to be peeled. */}
      <motion.div
        whileHover={
          still
            ? undefined
            : { scale: 1.08, rotate: s.rot > 0 ? 6 : -6, y: "-0.4cqw" }
        }
        transition={{ type: "spring", stiffness: 400, damping: 12 }}
        className="h-full w-full"
      >
        <Mark s={s} />
      </motion.div>
    </motion.div>
  );
}

export default function DeskLogos({
  p,
  still,
}: {
  p: MotionValue<number>;
  still: boolean;
}) {
  return (
    <div aria-hidden="true" className="absolute inset-0">
      {STICKERS.map((s, i) => (
        <Sticker key={s.name} p={p} i={i} s={s} still={still} />
      ))}
    </div>
  );
}
